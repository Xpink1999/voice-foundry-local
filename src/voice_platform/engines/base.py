from typing import Protocol, Iterator
import numpy as np

class SpeechEngine(Protocol):
    """Adapters own model imports, capabilities and lifecycle; return mono float PCM."""
    sample_rate: int
    def __init__(self, config: dict): ...
    def capabilities(self) -> dict: ...
    def identity(self) -> dict: ...
    def load(self) -> None: ...
    def unload(self) -> None: ...
    def synthesize(self, request: dict) -> Iterator[np.ndarray]: ...
