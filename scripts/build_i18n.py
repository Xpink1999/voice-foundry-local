"""Build the offline browser catalog from the four editable JSON catalogs."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ('zh-CN', 'en', 'ja', 'ko')


def build(root=ROOT):
    catalogs = {code: json.loads((root/'web/locales'/f'{code}.json').read_text(encoding='utf-8')) for code in LANGUAGES}
    base = catalogs['zh-CN']
    for code, catalog in catalogs.items():
        if set(catalog) != set(base):
            raise ValueError(f'{code}: translation keys differ')
        for key, value in catalog.items():
            if not isinstance(value, str) or not value.strip():
                raise ValueError(f'{code}: empty translation for {key}')
            if sorted(re.findall(r'\{\d+\}', key)) != sorted(re.findall(r'\{\d+\}', value)):
                raise ValueError(f'{code}: placeholders differ for {key}')
    target = root/'web/translations.js'
    target.write_text('// Generated by scripts/build_i18n.py; edit web/locales/*.json.\nwindow.voiceTranslations = '+json.dumps(catalogs, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c')+';\n', encoding='utf-8', newline='\n')
    print(f'{len(base)} messages, {len(catalogs)} languages')


if __name__ == '__main__':
    build()
